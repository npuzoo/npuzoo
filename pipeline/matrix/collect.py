#!/usr/bin/env python3
"""Merge per-job results into matrix/conversion.json and docs/conversion-matrix.md.

    python collect.py results/ --json matrix/conversion.json --md docs/conversion-matrix.md
"""
import argparse
import glob
import json
import os
import sys

TARGET_ORDER = ["rk3588", "rk3576", "rk3562", "rv1126b"]


def _vkey(v):
    try:
        return tuple(int(x) for x in (v or "0.0.0").split(".")[:3])
    except ValueError:
        return (0, 0, 0)


def load(folder):
    records = []
    for path in sorted(glob.glob(os.path.join(folder, "**", "*.json"), recursive=True)):
        try:
            with open(path, encoding="utf-8") as f:
                r = json.load(f)
        except (OSError, ValueError):
            continue
        if isinstance(r, dict) and "results" in r and r.get("model"):
            records.append(r)
    records.sort(key=lambda r: (r["model"].lower(), [-x for x in _vkey(r.get("toolkit"))]))
    return records


def merge(old, new):
    """New records replace old ones for the same model and toolkit; the rest are kept.

    A run that covers only some combinations (or is cancelled part-way) must
    not wipe the results of the others.
    """
    key = lambda r: (r["model"], r.get("toolkit"))
    merged = {key(r): r for r in old}
    merged.update({key(r): r for r in new})
    out = list(merged.values())
    out.sort(key=lambda r: (r["model"].lower(), [-x for x in _vkey(r.get("toolkit"))]))
    return out


def columns(records):
    cols = {(x["target"], x["dtype"]) for r in records for x in r["results"]}
    return sorted(cols, key=lambda c: (TARGET_ORDER.index(c[0]) if c[0] in TARGET_ORDER else 99, c[1]))


def cell(x):
    if x is None:
        return "—"
    if x["status"] == "ok":
        bits = []
        if x.get("bytes"):
            bits.append("%.2f GB" % (x["bytes"] / 1e9))
        if x.get("seconds") is not None:
            bits.append("%d min" % max(1, round(x["seconds"] / 60)))
        if x.get("peak_rss_gb"):
            bits.append("%.1f GB RAM" % x["peak_rss_gb"])
        if x.get("signature") and x["signature"] != "rkllm":
            bits.append("**unexpected file signature: %s**" % x["signature"])
        return ("✓ " + " · ".join(bits)).strip()
    return "✗ %s" % (x.get("stage") or "?")


def short(err, n=140):
    err = (err or "no error line captured").replace("|", "\\|").replace("\n", " ")
    return err if len(err) <= n else err[: n - 1] + "…"


def render(records):
    cols = columns(records)
    ok = sum(1 for r in records for x in r["results"] if x["status"] == "ok")
    total = sum(len(r["results"]) for r in records)
    dates = sorted(r["date"] for r in records if r.get("date"))
    runner = next((r["runner"] for r in records if r.get("runner", {}).get("cpus")), {})
    out = [
        "# Conversion matrix",
        "",
        "Which Hugging Face models convert to `.rkllm` with which rkllm-toolkit release, for which chip and",
        "weight format. **Conversion only — nothing here has been run on a board yet.** A ✓ means the toolkit",
        "produced a file with Rockchip's signature; it says nothing about speed or output quality.",
        "",
        "Generated by `.github/workflows/conversion-matrix.yml` from `pipeline/matrix/`; do not edit by hand.",
        "Raw results, including the log tail of every failure: [`matrix/conversion.json`](../matrix/conversion.json).",
        "",
        "- Run: %s" % (dates[-1] if dates else "?"),
        "- Machine: GitHub-hosted x86 runner, %s CPUs, %s GB RAM, no GPU; Python %s, torch %s (CPU build)" % (
            runner.get("cpus", "?"), runner.get("mem_gb", "?"), runner.get("python", "?"), runner.get("torch", "?")),
        "- Calibration: 8 prompts of our own (English and Chinese), answered by the model itself, in the format",
        "  of Rockchip's `generate_data_quant.py`. `max_context` 4096, `optimization_level` 1.",
        "- Result: %d of %d conversions produced a file." % (ok, total),
        "",
        "| Model | Toolkit | " + " | ".join("%s %s" % (t.upper(), d) for t, d in cols) + " |",
        "|---|---|" + "---|" * len(cols),
    ]
    for r in records:
        by = {(x["target"], x["dtype"]): x for x in r["results"]}
        out.append("| %s | %s | %s |" % (r["model"], r.get("toolkit") or "?",
                                        " | ".join(cell(by.get(c)) for c in cols)))
    fails = [(r, x) for r in records for x in r["results"] if x["status"] != "ok"]
    if fails:
        out += ["", "## Failures", "", "| Model | Toolkit | Target | Stage | Last error line |", "|---|---|---|---|---|"]
        for r, x in fails:
            out.append("| %s | %s | %s %s | %s | %s |" % (
                r["model"], r.get("toolkit") or "?", x["target"].upper(), x["dtype"],
                x.get("stage") or "?", short(x.get("error"))))
    out += ["", "Stages: `install` (the toolkit would not install), `download`, `import`, `load`",
            "(`load_huggingface`), `build` (quantization), `export`, `timeout`.", ""]
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("folder")
    ap.add_argument("--json", default="matrix/conversion.json")
    ap.add_argument("--md", default="docs/conversion-matrix.md")
    ap.add_argument("--merge", help="existing conversion.json to keep results from")
    a = ap.parse_args(argv)
    records = load(a.folder)
    if records and a.merge and os.path.exists(a.merge):
        with open(a.merge, encoding="utf-8") as f:
            records = merge(json.load(f).get("records", []), records)
    if not records:
        print("no results found in %s" % a.folder, file=sys.stderr)
        return 1
    for path in (a.json, a.md):
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(a.json, "w", encoding="utf-8") as f:
        json.dump({"schema": 1, "records": records}, f, ensure_ascii=False, indent=1)
        f.write("\n")
    with open(a.md, "w", encoding="utf-8") as f:
        f.write(render(records))
    print("%d records → %s, %s" % (len(records), a.json, a.md))
    return 0


if __name__ == "__main__":
    sys.exit(main())
